    card: float = Field(0.0, description="??????? ???????? POS / Visa / Mastercard")
    cliq: float = Field(0.0, description="??????? ???? ???? CliQ")
    delivery_apps: float = Field(0.0, description="??????? ??????? ??????? ??? ??????? ?????")
    bank_transfer: float = Field(0.0, description="??????? ????? ??????")
    other: float = Field(0.0, description="?? ????? ??? ????")

    @property
    def total_payments(self) -> float:
        return round(self.cash + self.card + self.cliq + self.delivery_apps + self.bank_transfer + self.other, 3)

